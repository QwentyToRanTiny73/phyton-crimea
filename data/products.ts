// ─── HELPERS ──────────────────────────────────────────────────────────────────

export function getProductBySlug(s: string): Product | undefined {
  return products.find((p) => p.slug === s);
}

export function getFeaturedProducts(count = 6): Product[] {
  return products.filter((p) => p.featured).slice(0, count);
}

export function getProductsByCategory(cat: ProductCategory): Product[] {
  return products.filter((p) => p.category === cat);
}

export function getRelatedProducts(product: Product, count = 4): Product[] {
  return products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, count);
}

export function getAllCategories(): ProductCategory[] {
  return Array.from(new Set(products.map((p) => p.category)));
}
